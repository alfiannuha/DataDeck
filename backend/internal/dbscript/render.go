package dbscript

import (
	"fmt"
	"io"
	"strings"

	"github.com/datadeck/datadeck/backend/internal/model"
)

// QuoteFor returns the identifier quote character for a driver.
func QuoteFor(driver string) string {
	if driver == "mysql" {
		return "`"
	}
	return `"`
}

// QuoteIdent quotes one identifier, doubling the quote character.
func QuoteIdent(quote, ident string) string {
	return quote + strings.ReplaceAll(ident, quote, quote+quote) + quote
}

func quoteList(quote string, columns []string) string {
	parts := make([]string, len(columns))
	for i, column := range columns {
		parts[i] = QuoteIdent(quote, column)
	}
	return strings.Join(parts, ", ")
}

func countSecondaryIndexes(structure model.TableStructure) int {
	count := 0
	for _, index := range structure.Indexes {
		if index.Primary {
			continue
		}
		if hasExpressionPart(index.Columns) {
			continue
		}
		count++
	}
	return count
}

func hasExpressionPart(columns []string) bool {
	for _, column := range columns {
		if strings.TrimSpace(column) == "" {
			return true
		}
	}
	return false
}

// RenderCreateTable writes one CREATE TABLE statement. Foreign keys are not
// included here (they are added after data for PostgreSQL/MySQL); SQLite cannot
// ALTER TABLE ADD CONSTRAINT, so its foreign keys are rendered inline.
func RenderCreateTable(w io.Writer, driver string, ref TableRef, structure model.TableStructure) error {
	quote := QuoteFor(driver)
	var b strings.Builder
	fmt.Fprintf(&b, "\nCREATE TABLE %s (\n", ref.qualified(driver))

	defs := make([]string, 0, len(structure.Columns)+4)
	for _, column := range structure.Columns {
		defs = append(defs, renderColumn(driver, quote, column))
	}
	if structure.PrimaryKey != nil && len(structure.PrimaryKey.Columns) > 0 {
		defs = append(defs, "  PRIMARY KEY ("+quoteList(quote, structure.PrimaryKey.Columns)+")")
	}
	for _, constraint := range structure.Constraints {
		if line, ok := renderTableConstraint(driver, quote, constraint); ok {
			defs = append(defs, line)
		}
	}
	if driver == "sqlite" {
		for _, fk := range structure.ForeignKeys {
			defs = append(defs, "  "+renderForeignKeyClause(quote, fk, referencedTable(quote, driver, ref, fk)))
		}
	}
	b.WriteString(strings.Join(defs, ",\n"))
	b.WriteString("\n);\n")
	_, err := io.WriteString(w, b.String())
	return err
}

func renderColumn(driver, quote string, column model.StructureColumn) string {
	columnType := strings.TrimSpace(column.DatabaseType)
	if columnType == "" {
		columnType = strings.TrimSpace(column.NormalizedType)
	}
	if columnType == "" {
		columnType = "text"
	}
	var b strings.Builder
	b.WriteString("  ")
	b.WriteString(QuoteIdent(quote, column.Name))
	b.WriteString(" ")
	b.WriteString(columnType)

	if column.Generated && column.Default != nil && *column.Default != "" {
		b.WriteString(" GENERATED ALWAYS AS (")
		b.WriteString(*column.Default)
		b.WriteString(") STORED")
		return b.String()
	}

	if !column.Nullable {
		b.WriteString(" NOT NULL")
	}
	if column.Default != nil && *column.Default != "" {
		b.WriteString(" DEFAULT ")
		b.WriteString(*column.Default)
	}
	if column.Identity {
		switch driver {
		case "postgres":
			b.WriteString(" GENERATED BY DEFAULT AS IDENTITY")
		case "mysql":
			b.WriteString(" AUTO_INCREMENT")
		}
		// SQLite rowid alias is expressed through the primary key clause.
	}
	return b.String()
}

func renderTableConstraint(driver, quote string, constraint model.StructureConstraint) (string, bool) {
	definition := strings.TrimSpace(constraint.Definition)
	switch constraint.Type {
	case "UNIQUE":
		if strings.HasPrefix(strings.ToUpper(definition), "UNIQUE") {
			return "  " + definition, true
		}
		if len(constraint.Columns) > 0 {
			return "  UNIQUE (" + quoteList(quote, constraint.Columns) + ")", true
		}
	case "CHECK":
		if strings.HasPrefix(strings.ToUpper(definition), "CHECK") {
			return "  " + definition, true
		}
		if definition != "" {
			return "  CHECK (" + definition + ")", true
		}
	}
	return "", false
}

// RenderIndexes writes the secondary CREATE INDEX statements for one table.
// Expression/partial indexes cannot be reproduced from the canonical metadata
// and are skipped (they are reported via the coverage matrix).
func RenderIndexes(w io.Writer, driver string, ref TableRef, structure model.TableStructure) error {
	quote := QuoteFor(driver)
	for _, index := range structure.Indexes {
		if index.Primary || hasExpressionPart(index.Columns) {
			continue
		}
		unique := ""
		if index.Unique {
			unique = "UNIQUE "
		}
		if _, err := fmt.Fprintf(w, "CREATE %sINDEX %s ON %s (%s);\n",
			unique,
			QuoteIdent(quote, index.Name),
			ref.qualified(driver),
			quoteList(quote, index.Columns),
		); err != nil {
			return err
		}
	}
	return nil
}

// RenderForeignKeys writes ALTER TABLE ... ADD CONSTRAINT ... FOREIGN KEY for a
// table. Only used for engines that support it (PostgreSQL/MySQL).
func RenderForeignKeys(w io.Writer, driver string, ref TableRef, structure model.TableStructure) error {
	quote := QuoteFor(driver)
	for _, fk := range structure.ForeignKeys {
		referenced := referencedTable(quote, driver, ref, fk)
		if _, err := fmt.Fprintf(w, "ALTER TABLE %s ADD CONSTRAINT %s %s;\n",
			ref.qualified(driver),
			QuoteIdent(quote, fk.Name),
			renderForeignKeyClause(quote, fk, referenced),
		); err != nil {
			return err
		}
	}
	return nil
}

func referencedTable(quote, driver string, ref TableRef, fk model.StructureForeignKey) string {
	name := QuoteIdent(quote, fk.ReferencedTable)
	if driver == "postgres" {
		schema := fk.ReferencedSchema
		if schema == "" {
			schema = ref.Schema
		}
		if schema != "" {
			return QuoteIdent(quote, schema) + "." + name
		}
	}
	return name
}

// renderForeignKeyClause renders the constraint body; referenced must already be
// the correctly quoted (and schema-qualified where applicable) table reference.
func renderForeignKeyClause(quote string, fk model.StructureForeignKey, referenced string) string {
	var b strings.Builder
	b.WriteString("FOREIGN KEY (")
	b.WriteString(quoteList(quote, fk.Columns))
	b.WriteString(") REFERENCES ")
	b.WriteString(referenced)
	b.WriteString(" (")
	b.WriteString(quoteList(quote, fk.ReferencedColumns))
	b.WriteString(")")
	if action := referentialAction(fk.OnDelete); action != "" {
		b.WriteString(" ON DELETE ")
		b.WriteString(action)
	}
	if action := referentialAction(fk.OnUpdate); action != "" {
		b.WriteString(" ON UPDATE ")
		b.WriteString(action)
	}
	return b.String()
}

func referentialAction(raw string) string {
	action := strings.ToUpper(strings.TrimSpace(raw))
	switch action {
	case "", "NO ACTION":
		return ""
	case "RESTRICT", "CASCADE", "SET NULL", "SET DEFAULT":
		return action
	default:
		return ""
	}
}
